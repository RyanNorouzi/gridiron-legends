import { describe, expect, it } from 'vitest';
import type { PlayerId } from '@/core/ids';
import type { League } from '@/franchise/types';
import type { DepthChart } from '@/teams/types';
import { RETURNER_POSITIONS, STARTER_COUNTS, validateDepthChart } from '@/teams/depth-chart';
import { rosterPlayers } from '@/franchise/roster';
import { validateLeague } from '@/franchise/league';
import { ChoiceDialog, ConfirmDialog } from '@/ui/franchise/kit/dialogs';
import {
  addCandidates, addToSlot, autoDepth, depthChips, depthIssues, isReturnSlot, moveInSlot, removeBlocker, removeFromSlot, setRankInSlot, slotIssueCounts,
  slotName, slotRows, swapInSlot, withDepthChart,
} from '@/ui/franchise/team/depth-model';
import { DepthTab, depthColumns } from '@/ui/franchise/team/depth-tab';
import { TableScreen } from '@/ui/franchise/team/tab-screen';
import { makeInput, pointerAt } from '../../render/fake-ctx';
import { baseLeague, mount, press, rcFor, topAs, userId } from './helpers';

const chartOf = (league: League): DepthChart => {
  const t = league.teams[userId(league)];
  if (!t) throw new Error('team');
  return t.depthChart;
};

describe('depth model', () => {
  it('lists a slot in playing order with starters, ratings and issues', () => {
    const league = baseLeague();
    const team = userId(league);
    const wr = slotRows(league, team, 'WR');
    expect(wr.map((r) => r.id)).toEqual(chartOf(league).WR);
    expect(wr.filter((r) => r.starter)).toHaveLength(STARTER_COUNTS.WR);
    const kr = slotRows(league, team, 'KR');
    expect(kr.every((r) => RETURNER_POSITIONS.includes(r.position))).toBe(true);
    expect(kr[0]?.rating).not.toBe(kr[0]?.overall);
    expect(isReturnSlot('PR')).toBe(true);
    expect(slotName('KR')).toBe('Kick Returner');
    expect(slotName('QB')).toBe('Quarterback');
    expect(depthChips(league, team)).toHaveLength(19);
    expect(slotRows(league, 't_x' as never, 'QB')).toEqual([]);
    expect(depthIssues(league, 't_x' as never)).toEqual([]);
  });
  it('moves, swaps, adds, removes and rebuilds without invalidating the league', () => {
    const league = baseLeague();
    const team = userId(league);
    const [a, b, c] = chartOf(league).WR as PlayerId[];
    if (!a || !b || !c) throw new Error('wrs');
    const down = moveInSlot(league, team, 'WR', a, 1);
    expect(down.ok).toBe(true);
    expect(chartOf(down.league).WR.slice(0, 2)).toEqual([b, a]);
    expect(moveInSlot(league, team, 'WR', a, -1).reason).toBe('Already first');
    const top = setRankInSlot(league, team, 'WR', c, 0);
    expect(chartOf(top.league).WR[0]).toBe(c);
    const swap = swapInSlot(league, team, 'WR', a, c);
    expect(chartOf(swap.league).WR.slice(0, 3)).toEqual([c, b, a]);
    expect(swapInSlot(league, team, 'WR', a, a).ok).toBe(false);
    expect(swapInSlot(league, team, 'QB', a, c).ok).toBe(false);
    const cand = addCandidates(league, team, 'KR');
    expect(cand.length).toBeGreaterThan(0);
    expect(cand.every((p) => RETURNER_POSITIONS.includes(p.position))).toBe(true);
    const add = addToSlot(league, team, 'KR', cand[0]?.id as PlayerId);
    expect(chartOf(add.league).KR).toContain(cand[0]?.id);
    expect(addToSlot(add.league, team, 'KR', cand[0]?.id as PlayerId).ok).toBe(false);
    const qb = chartOf(league).QB[0] as PlayerId;
    expect(addToSlot(league, team, 'KR', qb).reason).toContain('cannot return');
    expect(removeBlocker(add.league, team, 'KR', cand[0]?.id as PlayerId)).toBeNull();
    const removed = removeFromSlot(add.league, team, 'KR', cand[0]?.id as PlayerId);
    expect(chartOf(removed.league).KR).not.toContain(cand[0]?.id);
    expect(removeBlocker(league, team, 'WR', a)).toContain('own position');
    const crossId = addCandidates(league, team, 'C').find((p) => p.position === 'OG')?.id as PlayerId;
    const cross = addToSlot(league, team, 'C', crossId);
    expect(slotRows(cross.league, team, 'C').find((r) => r.id === crossId)?.outOfPosition).toBe(true);
    expect(depthIssues(cross.league, team).some((i) => i.kind === 'wrongPosition')).toBe(true);
    for (const r of [down, top, swap, add, removed, cross]) expect(validateLeague(r.league)).toEqual([]);
    const shuffled = withDepthChart(league, team, { ...chartOf(league), QB: [...chartOf(league).QB].reverse() });
    const auto = autoDepth(shuffled, team);
    expect(chartOf(auto.league).QB[0]).toBe(chartOf(league).QB[0]);
    expect(validateDepthChart(chartOf(auto.league), rosterPlayers(auto.league, team)).filter((i) => i.severity === 'error')).toEqual([]);
    const counts = slotIssueCounts(depthIssues(cross.league, team));
    expect(counts.C.warnings).toBeGreaterThan(0);
  });
});

describe('DepthTab', () => {
  it('switches slots with Left/Right, Y and taps and moves players through the row dialog', () => {
    const league = baseLeague();
    const { fc, screen } = mount(league, (f) => new DepthTab(f));
    const rc = rcFor(fc);
    screen.render(rc);
    expect(screen.slot).toBe('QB');
    press(fc, 'menuRight');
    expect(screen.slot).toBe('RB');
    press(fc, 'menuLeft');
    press(fc, 'menuLeft');
    expect(screen.slot).toBe('PR');
    press(fc, 'audible');
    expect(screen.slot).toBe('QB');
    expect(screen.showSlot('WR')).toBe(true);
    screen.render(rc);
    expect(screen.slotView.table.columns.find((c) => c.key === 'rtg')?.label).toBe('OVR');
    const [a, b] = chartOf(league).WR as PlayerId[];
    press(fc, 'confirm');
    const dialog = topAs(fc, ChoiceDialog);
    expect(dialog.list.items.find((i) => i.id === 'up')?.disabled).toBe(true);
    dialog.choose('down');
    expect(fc.commits.at(-1)?.reason).toBe('edit');
    expect(chartOf(fc.league()).WR.slice(0, 2)).toEqual([b, a]);
    expect(screen.slotView.table.rows[1]?.id).toBe(a);
    screen.showSlot('KR');
    expect(screen.slotView.table.columns.find((c) => c.key === 'rtg')?.label).toBe('RET');
    const chipView = screen.chips.lastView;
    const te = chipView?.tabs.find((t) => t.label === 'TE');
    if (!te) throw new Error('TE chip not visible');
    fc.tick(makeInput({ pointer: pointerAt(te.x + 1, (chipView?.rect.y ?? 0) + 2, true), device: 'touch' }));
    expect(screen.slot).toBe('TE');
  });
  it('swaps in swap mode, cancels with X and runs the tab menu', () => {
    const league = baseLeague();
    const { fc, screen } = mount(league, (f) => new DepthTab(f, { slot: 'CB' }));
    const [a, b, c] = chartOf(league).CB as PlayerId[];
    const rows = screen.slotView.table.rows;
    screen.rowAction('swap', rows[0] as never);
    expect(screen.swapping).toBe(a);
    expect(screen.summary().text).toContain('Swap');
    expect(screen.hints()[0]?.label).toBe('Swap here');
    screen.slotView.table.select(2);
    press(fc, 'confirm');
    expect(chartOf(fc.league()).CB.slice(0, 3)).toEqual([c, b, a]);
    screen.rowAction('swap', screen.slotView.table.rows[0] as never);
    press(fc, 'showPlayArt');
    expect(screen.swapping).toBeNull();
    expect(fc.toasts.at(-1)).toBe('Swap cancelled');
    screen.rowAction('card', screen.slotView.table.rows[0] as never);
    expect(fc.openedPlayers).toHaveLength(1);
    press(fc, 'pause');
    const menu = topAs(fc, ChoiceDialog);
    menu.choose('auto');
    topAs(fc, ConfirmDialog).choose(true);
    expect(fc.toasts.at(-1)).toContain('rebuilt');
    screen.showSlot('PR');
    screen.onMenu('add');
    const add = topAs(fc, ChoiceDialog);
    const first = add.list.items[0];
    if (!first) throw new Error('candidate');
    add.choose(first.id);
    expect(chartOf(fc.league()).PR).toContain(first.id);
    screen.showSlot('C');
    screen.onMenu('add');
    const cross = topAs(fc, ChoiceDialog);
    const og = cross.list.items.find((i) => i.subLabel?.startsWith('OG'));
    if (!og) throw new Error('OG candidate');
    cross.choose(og.id);
    screen.showSlot('QB');
    screen.onMenu('issues');
    const issues = topAs(fc, TableScreen);
    issues.render(rcFor(fc));
    expect(issues.view.table.rows.length).toBeGreaterThan(0);
    const target = (issues.view.table.selected as { slot?: string } | null)?.slot;
    press(fc, 'confirm');
    expect(fc.stack.top).toBe(screen);
    expect(screen.slot).toBe(target);
    const kr = new DepthTab(fc, { slot: 'KR' });
    expect(kr.slot).toBe('KR');
    expect(kr.slotView.table.columns.find((col) => col.key === 'rtg')?.label).toBe('RET');
    expect(kr.slotView.table.rows.map((r) => r.id)).toEqual(chartOf(fc.league()).KR);
    expect(depthColumns('QB', true).map((col) => col.key)).toEqual(['rank', 'name', 'pos', 'rtg', 'ovr', 'inj', 'fat']);
    expect(depthColumns('KR', false)).toHaveLength(5);
    const big = mount(league, (f) => new DepthTab(f), { settings: { textSize: 'large' } });
    big.screen.render(rcFor(big.fc));
    expect(big.screen.slotView.isWide).toBe(false);
  });
});
