import { describe, expect, it } from 'vitest';
import type { PlayerId } from '@/core/ids';
import { createContract, leagueCapYear, minimumSalaryFor, yearsRemainingAt } from '@/franchise/contracts';
import type { League } from '@/franchise/types';
import type { Player } from '@/players/types';
import { ChoiceDialog, ConfirmDialog, StepperDialog } from '@/ui/franchise/kit/dialogs';
import { PlayerCardScreen, actionsTable, cardSections, cardTabs } from '@/ui/franchise/player-card';
import { NegotiationScreen } from '@/ui/franchise/team/negotiation-screen';
import { compareColumns, restructureField, restructureSummary, runPlayerAction } from '@/ui/franchise/team/player-action-flows';
import { TableScreen } from '@/ui/franchise/team/tab-screen';
import { baseLeague, inPhase, mount, press, rcFor, topAs, userId, userPlayer, withPlayer } from './helpers';

const contracted = (league: League): Player => userPlayer(league, undefined, (p) => {
  const c = p.contract;
  return !!c && yearsRemainingAt(c, leagueCapYear(league)) >= 3 && c.salary > minimumSalaryFor(p.experience, league.settings) + 1_000_000;
});

describe('player card actions', () => {
  it('adds an Actions section only for the user roster', () => {
    const league = baseLeague();
    const p = contracted(league);
    const { fc, screen } = mount(league, (f) => new PlayerCardScreen(f, p.id));
    expect(screen.tabs.tabs.map((t) => t.id)).toContain('actions');
    expect(screen.actions).toHaveLength(7);
    const view = screen.view;
    if (!view) throw new Error('view');
    expect(cardTabs(view, false)).toEqual(cardSections(view));
    expect(screen.showSection('actions')).toBe(true);
    screen.render(rcFor(fc));
    expect(screen.hints().map((h) => h.label)).toContain('Actions');
    expect(actionsTable(screen.actions).rows).toHaveLength(7);
    const other = Object.values(league.teams).find((t) => t.id !== userId(league));
    const theirs = mount(league, (f) => new PlayerCardScreen(f, other?.rosterIds[0] as PlayerId));
    expect(theirs.screen.tabs.tabs.map((t) => t.id)).not.toContain('actions');
    expect(theirs.screen.openActionMenu()).toBeNull();
  });
  it('opens the action menu with Y and toggles the trading block', () => {
    const league = baseLeague();
    const p = contracted(league);
    const { fc, screen } = mount(league, (f) => new PlayerCardScreen(f, p.id));
    press(fc, 'audible');
    const menu = topAs(fc, ChoiceDialog);
    menu.render(rcFor(fc));
    menu.choose('block');
    expect(fc.commits.at(-1)?.reason).toBe('edit');
    expect(fc.league().club?.playerFlags[p.id]).toEqual(['tradeBlock']);
    expect(screen.actions.find((a) => a.id === 'block')?.label).toBe('Remove from trading block');
    expect(fc.toasts.at(-1)).toContain('trading block');
  });
  it('releases through the confirmation with the signing reason', () => {
    const league = baseLeague();
    const p = contracted(league);
    const { fc, screen } = mount(league, (f) => new PlayerCardScreen(f, p.id, { section: 'actions' }));
    expect(screen.section).toBe('actions');
    const row = screen.table?.rows.findIndex((r) => 'id' in r && r.id === 'release') ?? -1;
    screen.table?.select(row);
    press(fc, 'confirm');
    const confirm = topAs(fc, ConfirmDialog);
    expect(confirm.message).toContain('Dead money');
    confirm.choose(false);
    expect(fc.commits).toHaveLength(0);
    screen.runAction('release');
    topAs(fc, ConfirmDialog).choose(true);
    expect(fc.commits.at(-1)?.reason).toBe('signing');
    expect(fc.league().players[p.id]?.teamId).toBeNull();
    expect(screen.actions).toHaveLength(0);
    expect(screen.tabs.tabs.map((t) => t.id)).not.toContain('actions');
    expect(screen.view?.status).toBe('freeAgent');
  });
  it('restructures through the stepper and sets the training focus', () => {
    const league = baseLeague();
    const p = contracted(league);
    const { fc, screen } = mount(league, (f) => new PlayerCardScreen(f, p.id));
    expect(screen.runAction('restructure')).toBe(true);
    const stepper = topAs(fc, StepperDialog);
    expect(stepper.summary).toContain('Saves');
    stepper.render(rcFor(fc));
    press(fc, 'menuTabLeft');
    press(fc, 'confirm');
    expect(fc.commits.at(-1)?.reason).toBe('signing');
    expect(fc.league().players[p.id]?.contract?.restructured).toBe(true);
    expect(screen.runAction('focus')).toBe(true);
    const focus = topAs(fc, ChoiceDialog);
    const option = focus.list.items[1];
    if (!option) throw new Error('focus option');
    focus.choose(option.id);
    expect(fc.league().players[p.id]?.trainingFocus).toBe(option.id);
    expect(fc.commits.at(-1)?.reason).toBe('edit');
  });
  it('refuses disabled actions, tags in the re-signing window and opens compare / negotiation', () => {
    const league = baseLeague();
    const p = contracted(league);
    const { fc, screen } = mount(league, (f) => new PlayerCardScreen(f, p.id));
    expect(screen.runAction('tag')).toBe(false);
    expect(fc.toasts.at(-1)).toContain('offseason');
    expect(screen.runAction('compare')).toBe(true);
    const compare = topAs(fc, TableScreen);
    compare.render(rcFor(fc));
    expect(compare.view.table.rows.some((r) => (r as { self: boolean }).self)).toBe(true);
    press(fc, 'confirm');
    expect(fc.openedPlayers).toHaveLength(1);
    press(fc, 'back');
    expect(screen.runAction('extend')).toBe(true);
    expect(fc.stack.top).toBeInstanceOf(NegotiationScreen);
    const off = inPhase(league, 'resigning');
    const expiring = withPlayer(off, { ...p, contract: createContract({ salary: 4_000_000, years: 1, guaranteed: 0, signingBonus: 0, role: 'starter', year: off.year }) });
    const t = mount(expiring, (f) => new PlayerCardScreen(f, p.id));
    expect(t.screen.runAction('tag')).toBe(true);
    topAs(t.fc, ChoiceDialog).choose('transition');
    expect(t.fc.league().players[p.id]?.contract?.tag).toBe('transition');
    expect(t.fc.commits.at(-1)?.reason).toBe('signing');
    runPlayerAction(t.fc, p.id, 'block');
    expect(t.fc.commits).toHaveLength(2);
  });
  it('formats the restructure preview and the comparison columns', () => {
    expect(restructureSummary({ savings: 500_000, years: [{ year: 2026, before: 2e6, after: 1.5e6 }] })).toBe('Saves $500K this season');
    expect(restructureSummary({ savings: 500_000, years: [{ year: 2026, before: 2e6, after: 1.5e6 }, { year: 2027, before: 2e6, after: 1.5e6 }] })).toBe('Saves $500K now · later -$500K/yr');
    expect(restructureSummary({ savings: 1, years: [{ year: 1, before: 2, after: 1 }, { year: 2, before: 2, after: 3 }, { year: 3, before: 2, after: 2 }] })).toContain('+$1, $0');
    expect(restructureField(20_000).min).toBe(20_000);
    expect(compareColumns(['speed', 'agility', 'hands', 'catching'], true).map((c) => c.key)).toEqual(['name', 'age', 'ovr', 'pot', 'dep', 'speed', 'agility', 'hands', 'catching', 'hit']);
    expect(compareColumns(['speed', 'agility', 'hands', 'catching'], false)).toHaveLength(5);
  });
});
