import { describe, expect, it } from 'vitest';
import { userRosterIssues } from '@/franchise/roster-rules';
import { withClub } from '@/franchise/rivalries';
import { ROSTER_FILTERS, fatigueCell, filterRoster, injuryCell, rosterColumns, rosterDetail, rosterRows, rosterSummary } from '@/ui/franchise/team/roster-model';
import { RosterTab, rosterIssueSpec } from '@/ui/franchise/team/roster-tab';
import { TableScreen } from '@/ui/franchise/team/tab-screen';
import { ChoiceDialog } from '@/ui/franchise/kit/dialogs';
import { makeInput, pointerAt } from '../../render/fake-ctx';
import { baseLeague, mount, press, rcFor, topAs, userId, userPlayer, withPlayer } from './helpers';

describe('roster view-model', () => {
  it('builds one row per rostered player with contract, morale, injury and fatigue', () => {
    const league = baseLeague();
    const team = league.teams[userId(league)];
    const rows = rosterRows(league, userId(league));
    expect(rows).toHaveLength(team?.rosterIds.length ?? -1);
    const qb = userPlayer(league, 'QB');
    const row = rows.find((r) => r.id === qb.id);
    expect(row?.overall).toBe(qb.overall);
    expect(row?.potential.text).toBe(String(qb.potential));
    expect(row?.potentialSort).toBe(qb.potential);
    expect(row?.apy).toBeGreaterThan(0);
    expect(row?.yearsLeft).toBeGreaterThan(0);
    expect(row?.depthRank).toBeGreaterThanOrEqual(0);
    expect(filterRoster(rows, 'QB').every((r) => r.position === 'QB')).toBe(true);
    expect(filterRoster(rows, 'ST').every((r) => r.position === 'K' || r.position === 'P')).toBe(true);
    expect(filterRoster(rows, 'all')).toHaveLength(rows.length);
    expect(ROSTER_FILTERS.map((f) => f.id)).toContain('OL');
    expect(rosterRows(league, 't_nope' as never)).toEqual([]);
  });
  it('shows injuries, fatigue, flags and the summary', () => {
    const base = baseLeague();
    const p = userPlayer(base, 'RB');
    const hurt = withPlayer(base, { ...p, injury: { bodyArea: 'lowerBody', severity: 'short', weeksRemaining: 3, permanentPenalty: null, occurredYear: base.year, occurredWeek: 1 } });
    const league = withClub({ ...hurt, fatigue: { [p.id]: 0.6 } }, { playerFlags: { [p.id]: ['tradeBlock'] } });
    const row = rosterRows(league, userId(league)).find((r) => r.id === p.id);
    if (!row) throw new Error('row');
    expect(injuryCell(row.injury)).toEqual({ text: '3w', tone: 'danger' });
    expect(injuryCell(null).text).toBe('-');
    expect(fatigueCell(row.fatigue)).toEqual({ text: '60%', tone: 'danger' });
    expect(fatigueCell(0.3).tone).toBe('warning');
    expect(rosterDetail(row).text).toContain('Trade Block');
    expect(rosterDetail(row).tone).toBe('warning');
    const name = rosterColumns(true).find((c) => c.key === 'name');
    expect(name?.format(row)).toEqual({ text: `${row.name} (TB)`, tone: 'info' });
    expect(rosterColumns(false).map((c) => c.key)).toEqual(['name', 'pos', 'ovr', 'pot', 'apy', 'inj']);
    expect(rosterColumns(true)).toHaveLength(10);
    const summary = rosterSummary(league, userId(league));
    expect(summary.text).toContain('players');
    expect(summary.text).toContain('Cap space');
    expect(rosterSummary(league, 't_nope' as never).tone).toBe('danger');
  });
});

describe('RosterTab', () => {
  it('filters with Y and taps, sorts, opens the player card and renders in both text sizes', () => {
    const league = baseLeague();
    const { fc, screen } = mount(league, (f) => new RosterTab(f));
    const rc = rcFor(fc);
    screen.render(rc);
    expect(rc.ctx.fills.length).toBeGreaterThan(300);
    expect(screen.lastLayout?.summary).not.toBeNull();
    expect(screen.roster.table.rows.length).toBe(league.teams[userId(league)]?.rosterIds.length);
    press(fc, 'audible');
    expect(screen.chips.current).toBe('QB');
    expect(screen.roster.table.rows.every((r) => r.position === 'QB')).toBe(true);
    screen.render(rc);
    const chipView = screen.chips.lastView;
    const ol = chipView?.tabs.find((t) => t.label === 'OL');
    if (!ol) throw new Error('chips');
    fc.tick(makeInput({ pointer: pointerAt(ol.x + 2, (chipView?.rect.y ?? 0) + 3, true), device: 'touch' }));
    expect(screen.chips.current).toBe('OL');
    press(fc, 'menuRight');
    expect(screen.roster.table.sortKey).not.toBe('pos');
    press(fc, 'menuDown');
    press(fc, 'confirm');
    expect(fc.openedPlayers).toHaveLength(1);
    expect(screen.roster.table.rows.map((r) => r.id)).toContain(fc.openedPlayers[0]);
    press(fc, 'back');
    press(fc, 'menuTabRight');
    expect(fc.pops()).toBe(0);
    expect(screen.chips.current).toBe('OL');
    expect(screen.hints().map((h) => h.label)).toEqual(['Card', 'Filter', 'Sort']);
    const big = mount(league, (f) => new RosterTab(f), { settings: { textSize: 'large' } });
    const rcBig = rcFor(big.fc);
    big.screen.render(rcBig);
    expect(big.screen.roster.isWide).toBe(false);
    expect(big.screen.roster.table.visibleRows).toBeGreaterThanOrEqual(3);
  });
  it('lists roster issues from the tab menu (Start or a tap on the menu button)', () => {
    const base = baseLeague();
    const team = base.teams[userId(base)];
    if (!team) throw new Error('team');
    const cut = { ...base, teams: { ...base.teams, [team.id]: { ...team, rosterIds: team.rosterIds.slice(0, 40) } } };
    const issues = userRosterIssues(cut, team.id);
    expect(issues.length).toBeGreaterThan(0);
    const { fc, screen } = mount(cut, (f) => new RosterTab(f));
    expect(screen.menu()[0]?.disabled).toBe(false);
    screen.render(rcFor(fc));
    const menu = screen.lastLayout?.menu;
    if (!menu) throw new Error('menu button');
    fc.tick(makeInput({ pointer: pointerAt(menu.x + 2, menu.y + 2, true), device: 'mouse' }));
    const dialog = topAs(fc, ChoiceDialog);
    dialog.choose('issues');
    const table = topAs(fc, TableScreen);
    expect(table.view.table.rows).toHaveLength(issues.length);
    table.render(rcFor(fc));
    press(fc, 'back');
    expect(fc.stack.top).toBe(screen);
    const spec = rosterIssueSpec(() => issues);
    expect(spec.rows()[0]?.id).toBe('issue-0');
    const clean = mount(base, (f) => new RosterTab(f));
    expect(clean.screen.menu()[0]?.disabled).toBe(userRosterIssues(base, team.id).length === 0);
    press(clean.fc, 'pause');
    clean.screen.onMenu('unknown');
    expect(clean.fc.stack.size).toBeGreaterThanOrEqual(1);
  });
});
